/**
 * Render the store assets from the real product surfaces.
 *
 * Honesty rules this harness follows, because store screenshots are
 * representations and a fabricated one is a misrepresentation:
 *
 *   - Every panel shown is the real page, loaded live in an iframe, driven by
 *     the repository's own fixtures. Nothing is mocked up in a design tool.
 *   - The verdicts, digests and counts on screen are computed at capture time
 *     by the same WASM engine the product ships.
 *   - Nothing imitates Excel or Google Sheets chrome. These are product shots
 *     of the add-in's own pane, not composites pretending to be inside a host
 *     application. See README.md for why that matters for submission.
 *
 * Usage:  node tools/store-assets/capture.mjs
 */
