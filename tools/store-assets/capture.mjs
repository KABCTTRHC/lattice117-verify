/* The two host APIs the panes expect. Stubbed only far enough for the page to
   render its own UI; nothing here supplies data or fakes a result. */
const HOST_STUBS = `
  window.Office = {
    onReady: (cb) => cb({ host: 'Excel', platform: 'PC' }),
    HostType: { Excel: 'Excel' },
  };
  /* readSelection() returns getDisplayValues() — a 2-D array of the strings the
     user sees. The stub hands back the repository's own rota fixture in exactly
     that shape, so the sidebar evaluates real data with the real engine and the
     digest on screen is the one the white paper cites. Nothing is faked past
     the host boundary. */
  window.__L117_ROWS__ = ROWS_JSON;
  window.google = { script: { run: (function () {
    const api = {
      withSuccessHandler(cb) { api._ok = cb; return api; },
      withFailureHandler(cb) { api._fail = cb; return api; },
      readSelection() { setTimeout(() => api._ok && api._ok(window.__L117_ROWS__), 60); },
      highlightRows() {}, clearHighlighting() {},
    };
    return api;
  })() } };
`;

const frame = (opts) => {
  const p = new URLSearchParams(opts);
  return `${BASE}/tools/store-assets/frame.html?${p}`;
};

async function shoot({ name, url, dir, width, height, prepare, waitFor }) {
  const ctx = await browser.newContext({
    viewport: { width, height }, deviceScaleFactor: 1,
  });
  await ctx.addInitScript(HOST_STUBS.replace('ROWS_JSON', JSON.stringify(ROTA_ROWS)));
  if (LICENCE) {
    await ctx.addInitScript((key) => {
      try { localStorage.setItem('lattice117.licence', key); } catch { /* blocked */ }
    }, LICENCE);
  }
  const page = await ctx.newPage();
  const errs = [];
  page.on('pageerror', (e) => errs.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
  page.on('response', (r) => {
    if (r.status() === 404 && !/favicon/i.test(r.url())) errs.push(`404 ${r.url()}`);
  });

  await page.goto(url, { waitUntil: 'networkidle' });
  if (prepare) await prepare(page);
  if (waitFor) {
    try { await waitFor(page); }
    catch (e) { problems.push(`${name}: ${e.message}`); }
  }
  await page.waitForTimeout(700);

  const file = join(dir, name);
  await page.screenshot({ path: file });
  const real = errs.filter((e) =>
    !/office\.js|Office is not defined|favicon/i.test(e) &&
    !/Failed to load resource/i.test(e));   // the 404 listener reports the URL instead
  console.log(`  ${name.padEnd(34)} ${width}x${height}` + (real.length ? `  ERRORS: ${real[0]}` : ''));
  if (real.length) problems.push(`${name}: ${real[0]}`);
  await ctx.close();
}

/* Drive the browser page inside the frame's iframe, using its own buttons. */
const inFrame = (fn) => async (page) => {
  const f = page.frames().find((x) => x !== page.mainFrame());
  if (!f) throw new Error('iframe never attached');
  await fn(f);
};

/* The page hides the inactive tab's panel, so its buttons are present but not
   clickable. Select the tab first — the same way a user would. */
async function openTab(f, tab) {
  await f.click(`.tab[data-tab="${tab}"]`, { timeout: 15000 });
  await f.waitForTimeout(400);
}

/* The real user flow, which is three steps and not one: pick the tab, load the
   example, then confirm the column mapping. #runCsv is shared between modes and
   relabels itself ("Audit this sheet" / "Check this rota").

   The loader buttons start disabled and are enabled once the WASM module is
   ready, so this waits on that rather than sleeping and hoping. */
async function loadFixture(f, tab, loadButton, readyPanel) {
  await openTab(f, tab);
  await f.waitForSelector(`${loadButton}:not([disabled])`, { timeout: 25000 });
  await f.click(loadButton);
  await f.waitForSelector('#mapper', { state: 'visible', timeout: 15000 });
  await f.waitForTimeout(350);
  await f.click('#runCsv');
  // Fleet verdicts render into #resultPanel, rota into #rotaPanel.
  await f.waitForSelector(readyPanel, { state: 'visible', timeout: 20000 });
  await f.waitForTimeout(900);
}

